-- ============================================================
-- ANALYTICS DO BRECHÓ
-- Registra interações públicas para o painel do proprietário.
-- ============================================================
create table if not exists public.brecho_eventos (
  id bigint generated by default as identity primary key,
  brecho_id uuid not null references public.brechos(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  tipo text not null,
  created_at timestamptz not null default now()
);

alter table public.brecho_eventos enable row level security;

-- Visitantes podem registrar apenas eventos simples; se estiverem logados,
-- o user_id enviado precisa corresponder ao usuário autenticado.
drop policy if exists "eventos_public_insert" on public.brecho_eventos;
create policy "eventos_public_insert"
on public.brecho_eventos for insert
with check (user_id is null or user_id = auth.uid());

-- O dono só enxerga os eventos do próprio brechó; admin enxerga todos.
drop policy if exists "eventos_owner_select" on public.brecho_eventos;
create policy "eventos_owner_select"
on public.brecho_eventos for select
using (
  public.is_admin()
  or exists (
    select 1 from public.brechos b
    where b.id = brecho_eventos.brecho_id
      and (b.user_id = auth.uid() or b.dono_id = auth.uid())
  )
);

create index if not exists idx_brecho_eventos_brecho_id on public.brecho_eventos(brecho_id);
create index if not exists idx_brecho_eventos_tipo on public.brecho_eventos(tipo);
create index if not exists idx_brecho_eventos_created_at on public.brecho_eventos(created_at);

