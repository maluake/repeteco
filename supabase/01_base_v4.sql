alter table public.curtidas enable row level security;
alter table public.salvos enable row level security;

-- Profiles: cada pessoa lê o próprio perfil; admin lê todos.
drop policy if exists "profiles_select_own_or_admin" on public.profiles;
create policy "profiles_select_own_or_admin"
on public.profiles for select
using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own"
on public.profiles for insert
with check (id = auth.uid());

drop policy if exists "profiles_update_own_or_admin" on public.profiles;
create policy "profiles_update_own_or_admin"
on public.profiles for update
using (id = auth.uid() or public.is_admin())
with check (id = auth.uid() or public.is_admin());

-- Brechós: público vê somente aprovados; usuário cria o próprio; dono edita o próprio; admin gerencia tudo.
drop policy if exists "brechos_public_read_approved" on public.brechos;
create policy "brechos_public_read_approved"
on public.brechos for select
using (status in ('approved','aprovado','aprovada') or user_id = auth.uid() or dono_id = auth.uid() or public.is_admin());

drop policy if exists "brechos_insert_own" on public.brechos;
create policy "brechos_insert_own"
on public.brechos for insert
with check (user_id = auth.uid());

drop policy if exists "brechos_update_owner_or_admin" on public.brechos;
create policy "brechos_update_owner_or_admin"
on public.brechos for update
using (user_id = auth.uid() or dono_id = auth.uid() or public.is_admin())
with check (user_id = auth.uid() or dono_id = auth.uid() or public.is_admin());

drop policy if exists "brechos_delete_owner_or_admin" on public.brechos;
create policy "brechos_delete_owner_or_admin"
on public.brechos for delete
using (user_id = auth.uid() or dono_id = auth.uid() or public.is_admin());

