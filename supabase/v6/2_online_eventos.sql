-- ------------------------------------------------------------
-- Eventos (somente a equipe cria)
-- ------------------------------------------------------------
create table if not exists public.eventos (
  id uuid primary key default gen_random_uuid(),
  slug text unique,
  titulo text not null check (char_length(titulo) between 3 and 140),
  resumo text check (char_length(resumo) <= 280),
  descricao text not null default '',
  data_inicio timestamptz not null,
  data_fim timestamptz,
  formato text not null default 'presencial' check (formato in ('presencial', 'online', 'hibrido')),
  local_nome text check (char_length(local_nome) <= 120),
  endereco text check (char_length(endereco) <= 200),
  bairro text check (char_length(bairro) <= 80),
  cidade text default 'São Paulo',
  link text check (char_length(link) <= 400),
  capa_url text,
  capa_path text,
  capa_alt text check (char_length(capa_alt) <= 240),
  aceita_parcerias boolean not null default true,
  status text not null default 'rascunho' check (status in ('rascunho', 'publicado')),
  criado_por uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (data_fim is null or data_fim >= data_inicio)
);

create index if not exists idx_eventos_status_data on public.eventos(status, data_inicio);

create or replace function public.eventos_prepare()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  base text;
begin
  if new.slug is null or new.slug = '' then
    base := public.slugify(new.titulo);
    new.slug := base;
    if exists (select 1 from public.eventos where slug = new.slug and id <> new.id) then
      new.slug := base || '-' || left(replace(new.id::text, '-', ''), 6);
    end if;
  else
    new.slug := public.slugify(new.slug);
  end if;
  if tg_op = 'INSERT' and new.criado_por is null then
    new.criado_por := auth.uid();
  end if;
  if tg_op = 'UPDATE' then
    new.updated_at := now();
  end if;
  return new;
end;
$$;

drop trigger if exists eventos_prepare on public.eventos;
create trigger eventos_prepare
before insert or update on public.eventos
for each row execute function public.eventos_prepare();

alter table public.eventos enable row level security;

drop policy if exists "eventos_select" on public.eventos;
create policy "eventos_select"
on public.eventos for select
using (status = 'publicado' or public.is_admin());

drop policy if exists "eventos_admin_insert" on public.eventos;
create policy "eventos_admin_insert" on public.eventos for insert with check (public.is_admin());

drop policy if exists "eventos_admin_update" on public.eventos;
create policy "eventos_admin_update" on public.eventos for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "eventos_admin_delete" on public.eventos;
create policy "eventos_admin_delete" on public.eventos for delete using (public.is_admin());

-- ------------------------------------------------------------
-- Interesse em parceria (qualquer pessoa envia; só a equipe lê)
-- ------------------------------------------------------------
create table if not exists public.evento_parcerias (
  id bigint generated by default as identity primary key,
  evento_id uuid not null references public.eventos(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  brecho_id uuid references public.brechos(id) on delete set null,
  nome text not null check (char_length(nome) between 2 and 80),
  email text not null check (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' and char_length(email) <= 160),
  telefone text check (char_length(telefone) <= 30),
  tipo text not null default 'expositor' check (tipo in ('expositor', 'apoio', 'patrocinio', 'divulgacao', 'voluntariado', 'outro')),
  mensagem text check (char_length(mensagem) <= 2000),
  status text not null default 'nova' check (status in ('nova', 'em_conversa', 'confirmada', 'recusada')),
  created_at timestamptz not null default now()
);

create index if not exists idx_evento_parcerias_evento on public.evento_parcerias(evento_id);

create or replace function public.evento_aceita_parcerias(p_evento_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.eventos
    where id = p_evento_id and status = 'publicado' and aceita_parcerias
      and coalesce(data_fim, data_inicio) >= now() - interval '1 day'
  );
$$;

alter table public.evento_parcerias enable row level security;

drop policy if exists "parcerias_insert_any" on public.evento_parcerias;
create policy "parcerias_insert_any"
on public.evento_parcerias for insert
with check (
  (user_id is null or user_id = auth.uid())
  and status = 'nova'
  and public.evento_aceita_parcerias(evento_id)
  and (brecho_id is null or public.is_owner_of_brecho(brecho_id))
);

drop policy if exists "parcerias_select_own_or_admin" on public.evento_parcerias;
create policy "parcerias_select_own_or_admin"
on public.evento_parcerias for select
using (user_id = auth.uid() or public.is_admin());

drop policy if exists "parcerias_admin_update" on public.evento_parcerias;
create policy "parcerias_admin_update" on public.evento_parcerias for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "parcerias_admin_delete" on public.evento_parcerias;
create policy "parcerias_admin_delete" on public.evento_parcerias for delete using (public.is_admin());
